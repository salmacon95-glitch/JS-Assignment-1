// empty array
let marketBasket = []; 
 
// push() to add 
marketBasket.push("Rice", "Palm Oil", "Onions"); 
 
// pop() to remove the last item 
marketBasket.pop(); 
 
// unshift to add at the beginning 

marketBasket.unshift("Pepper"); 
marketBasket.unshift("Salt"); 
 
//  shift remove first item
marketBasket.shift(); 
 
console.log("Final Market Basket:", marketBasket); 